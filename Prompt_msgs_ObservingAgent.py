import asyncio
import os
from dotenv import load_dotenv
from PIL import Image as PILImage

# AutoGen v0.4 Imports
from autogen_agentchat.agents import AssistantAgent
from autogen_agentchat.base import TaskResult
from autogen_agentchat.conditions import MaxMessageTermination
from autogen_agentchat.messages import TextMessage, MultiModalMessage
from autogen_agentchat.teams import RoundRobinGroupChat
from autogen_ext.models.openai import OpenAIChatCompletionClient
from autogen_core import Image

# 1. Load environment setup
load_dotenv()
api_key = os.getenv("OPENAI_API_KEY")

if not api_key:
    raise ValueError("OPENAI_API_KEY environment variable is not set in .env")

async def main():
    # 2. Configure Model Client
    model_client = OpenAIChatCompletionClient(
        model="gpt-4o",
        api_key=api_key,
    )

    # 3. Prompt Engineering & Agent Definitions
    vision_analyzer = AssistantAgent(
        name="VisionAnalyzer",
        model_client=model_client,
        system_message="""
        You are a specialized Multimodal Data Analyst.
        PROMPT INSTRUCTIONS:
        1. Examine both text queries and attached images carefully.
        2. Provide exact facts and key characteristics observed in the inputs.
        3. Do NOT make unverified assumptions outside what is visible or stated.
        """,
    )

    observer_agent = AssistantAgent(
        name="ObservingAgent",
        model_client=model_client,
        system_message="""
        You are an Observing and Quality-Assurance Agent.
        PROMPT INSTRUCTIONS:
        1. Monitor and audit the outputs generated by VisionAnalyzer.
        2. Highlight any discrepancies or missed details.
        3. Provide a final stamp: [APPROVED] or [REVISION NEEDED] with concise reasoning.
        """,
    )

    # 4. Generate local image in-memory
    pil_img = PILImage.new("RGB", (300, 300), color=(34, 139, 34))
    sample_image = Image.from_pil(pil_img)

    multimodal_msg = MultiModalMessage(
        content=[
            "Describe what you see in this image and assess its suitability for a nature brochure.",
            sample_image,
        ],
        source="user",
    )

    # 5. Define Team and Termination
    termination = MaxMessageTermination(max_messages=2)
    
    team = RoundRobinGroupChat(
        participants=[vision_analyzer, observer_agent],
        termination_condition=termination,
    )

    # 6. Run Stream safely checking for TaskResult
    print("\n--- Running AutoGen Multimodal Pipeline with Observing Agent ---\n")
    
    stream = team.run_stream(task=multimodal_msg)
    
    async for item in stream:
        if isinstance(item, TaskResult):
            print("--- Execution Completed ---")
            break
            
        print(f"[{item.source.upper()}]:")
        if isinstance(item, TextMessage):
            print(f"{item.content}\n")
        elif isinstance(item, MultiModalMessage):
            print(f"[Multimodal Message Received with {len(item.content)} items]\n")
        else:
            print(f"{item}\n")

if __name__ == "__main__":
    asyncio.run(main())